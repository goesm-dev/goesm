// goesm's patch of encoding/json's v2_encode.go. Marshal encodes values of
// plain types (no methods, plain json tags) in one pass in the runtime
// (jsonMarshal in runtime/src/json.ts), and everything else with the
// encoder of encoding/json's own implementation (GOEXPERIMENT=nojsonv2,
// encode.go), changed to write and return what json v2 with v1 options
// writes and returns: its errors (a MarshalerError names the pointer type,
// as json v2 calls methods on addressable copies), the map keys it accepts
// and its text for invalid UTF-8. json v2 itself encodes only in programs
// whose types have its own methods (jsonV2, v2_decode.go).
package json

