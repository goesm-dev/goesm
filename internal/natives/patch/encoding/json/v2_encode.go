// ---- tags.go ----

// tagOptions are the options of a struct field's json tag that the legacy
// encoder and decoder use.
type tagOptions struct {
	omitEmpty, omitZero, quoted, embed, caseStrict, format bool
}

// parseTag parses a struct field's json tag as json v2 does
// (parseFieldOptions in encoding/json/v2's fields.go), which accepts
// almost any name, and returns the name ("" if the tag gives none) and
// the options. json v2 with v1 options ignores the errors of malformed tags.
func parseTag(tag string) (string, tagOptions) {
	var name string
	var opts tagOptions
	if len(tag) > 0 && !strings.HasPrefix(tag, ",") {
		n := len(tag) - len(strings.TrimLeftFunc(tag, func(r rune) bool {
			return !strings.ContainsRune(",\\'\"`", r) // reserve comma, backslash, and quotes
		}))
		name = tag[:n]
		ok := true
		if !strings.HasPrefix(tag[n:], ",") && len(name) != len(tag) {
			name, n, ok = consumeTagOption(tag, false)
		}
		if !utf8.ValidString(name) {
			name = string([]rune(name)) // replace invalid UTF-8 with utf8.RuneError
		}
		if !ok {
			name = ""
		}
		tag = tag[n:]
	}
	for len(tag) > 0 {
		if tag[0] == ',' {
			tag = tag[len(","):]
			if len(tag) == 0 {
				break
			}
		}
		opt, n, _ := consumeTagOption(tag, false)
		tag = tag[n:]
		switch opt {
		case "case":
			if !strings.HasPrefix(tag, ":") {
				break
			}
			tag = tag[len(":"):]
			opt, n, ok := consumeTagOption(tag, false)
			if !ok {
				break
			}
			tag = tag[n:]
			if opt == "strict" {
				opts.caseStrict = true
			}
		case "embed":
			opts.embed = true
		case "omitzero":
			opts.omitZero = true
		case "omitempty":
			opts.omitEmpty = true
		case "string":
			opts.quoted = true
		case "format":
			if !strings.HasPrefix(tag, ":") {
				break
			}
			tag = tag[len(":"):]
			opt, n, ok := consumeTagOption(tag, true)
			if ok && opt != "" {
				tag = tag[n:]
				opts.format = true
			}
		}
	}
	return name, opts
}

// consumeTagOption consumes the next option, which is either a Go
// identifier or a single-quoted string, as json v2 does. If the next option
// is invalid, it returns all of in until the next comma, and false.
func consumeTagOption(in string, allowQuoted bool) (string, int, bool) {
	i := strings.IndexByte(in, ',')
	if i < 0 {
		i = len(in)
	}
	switch r, _ := utf8.DecodeRuneInString(in); {
	case r == '_' || unicode.IsLetter(r):
		n := len(in) - len(strings.TrimLeftFunc(in, isLetterOrDigit))
		return in[:n], n, true
	case r == '\'' && allowQuoted:
		var inEscape bool
		b := []byte{'"'}
		n := len(`'`)
		for len(in) > n {
			r, rn := utf8.DecodeRuneInString(in[n:])
			switch {
			case inEscape:
				if r == '\'' {
					b = b[:len(b)-1] // remove escape character: `\'` => `'`
				}
				inEscape = false
			case r == '\\':
				inEscape = true
			case r == '"':
				b = append(b, '\\') // insert escape character: `"` => `\"`
			case r == '\'':
				b = append(b, '"')
				n += len(`'`)
				out, err := strconv.Unquote(string(b))
				if err != nil {
					return in[:i], i, false
				}
				return out, n, true
			}
			b = append(b, in[n:][:rn]...)
			n += rn
		}
	}
	return in[:i], i, false
}

func isLetterOrDigit(r rune) bool {
	return r == '_' || unicode.IsLetter(r) || unicode.IsNumber(r)
}

// ---- fold.go ----

// foldName returns a folded string such that foldName(x) == foldName(y)
// is identical to bytes.EqualFold(x, y).
func foldName(in []byte) []byte {
	// This is inlinable to take advantage of "function outlining".
	var arr [32]byte // large enough for most JSON names
	return appendFoldedName(arr[:0], in)
}

func appendFoldedName(out, in []byte) []byte {
	for i := 0; i < len(in); {
		// Handle single-byte ASCII.
		if c := in[i]; c < utf8.RuneSelf {
			if 'a' <= c && c <= 'z' {
				c -= 'a' - 'A'
			}
			out = append(out, c)
			i++
			continue
		}
		// Handle multi-byte Unicode.
		r, n := utf8.DecodeRune(in[i:])
		out = utf8.AppendRune(out, foldRune(r))
		i += n
	}
	return out
}

// foldRune returns the smallest rune for all runes in the same fold set.
func foldRune(r rune) rune {
	for {
		r2 := unicode.SimpleFold(r)
		if r2 <= r {
			return r2
		}
		r = r2
	}
}
