// marshalLegacy is Marshal with the encoder of encoding/json's own
// implementation (GOEXPERIMENT=nojsonv2), with json v2's errors.
func marshalLegacy(v any) ([]byte, error) {
	e := newEncodeState()
	defer encodeStatePool.Put(e)
	err := e.marshal(v, encOpts{escapeHTML: true})
	if err != nil {
		return nil, err
	}
	buf := append([]byte(nil), e.Bytes()...)
	return buf, nil
}

